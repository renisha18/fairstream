// Copies FairStream's address, deploy block and event signatures from
// ../shared/deployments.json into config.yaml.
//
// Why a copy: Envio Cloud only sees files inside indexer/, so config.yaml can't point
// outside it. Run `npm run sync` again after every redeploy of the contracts.
import { readFileSync, writeFileSync } from "node:fs";

const EVENTS = ["Deposited", "MeterKeySet", "SessionSettled", "WithdrawRequested", "Withdrawn"];

const deployments = JSON.parse(readFileSync(new URL("../../shared/deployments.json", import.meta.url), "utf8"));
const fairStream = deployments.contracts.FairStream;

// "SessionSettled(address indexed viewer, bytes32 indexed sessionId, uint256 requested, uint256 charged)"
function signature(name) {
  const item = fairStream.abi.find((x) => x.type === "event" && x.name === name);
  if (!item) throw new Error(`event ${name} is not in the FairStream ABI`);
  const params = item.inputs.map((i) => `${i.type}${i.indexed ? " indexed" : ""} ${i.name}`).join(", ");
  return `${name}(${params})`;
}

const config = `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# Generated by scripts/sync-deployment.mjs from shared/deployments.json. Don't edit by hand.
name: fairstream-indexer
description: FairStream payments on Monad testnet
contracts:
  - name: FairStream
    handler: src/EventHandlers.ts
    events:
${EVENTS.map((e) => `      - event: "${signature(e)}"`).join("\n")}
chains:
  - id: ${deployments.chainId} # Monad testnet, read through HyperSync
    start_block: ${fairStream.deployBlock} # the block FairStream was deployed in
    contracts:
      - name: FairStream
        address: "${fairStream.address}"
`;

writeFileSync(new URL("../config.yaml", import.meta.url), config);
console.log(`config.yaml: FairStream ${fairStream.address} on chain ${deployments.chainId} from block ${fairStream.deployBlock}`);
